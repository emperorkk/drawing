// Rewrites public/sw.js with the current file list and a new version.
// Run after any change to lessons, audio or the page:  node scripts/update-sw.js
const fs = require("fs"), path = require("path");
const pub = path.join(__dirname, "..", "public");
const audio = fs.readdirSync(path.join(pub, "audio")).filter(f => f.endsWith(".mp3")).sort().map(f => "audio/" + f);
const files = ["./", "lessons.js", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png", ...audio];
const version = "zografizo-" + new Date().toISOString().replace(/[-:T]/g, "").slice(0, 12);

const sw = `// Generated by scripts/update-sw.js. Do not edit by hand.
// The page and lessons load from the network first (so updates show right away),
// voice clips and icons come from the cache (so the app works offline).
const VERSION = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files, null, 0)};

self.addEventListener('install', e => {
  // cache: 'reload' skips the browser's HTTP cache, so a new version never stores old files.
  e.waitUntil(caches.open(VERSION).then(c => Promise.all(FILES.map(u =>
    fetch(new Request(u, { cache: 'reload' })).then(r => { if (!r.ok) throw new Error(u + ' ' + r.status); return c.put(u, r); })
  ))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

function networkFirst(req, key) {
  return fetch(req, { cache: 'no-cache' }).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(key, copy)); }
    return res;
  }).catch(() => caches.match(key, { ignoreSearch: true }));
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (req.mode === 'navigate') return e.respondWith(networkFirst(req, './'));
    if (url.pathname.endsWith('/lessons.js')) return e.respondWith(networkFirst(req, 'lessons.js'));
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => {
    if (res.ok && url.hostname.includes('fonts.g')) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
    return res;
  })));
});
`;
fs.writeFileSync(path.join(pub, "sw.js"), sw);
console.log("sw.js:", version, files.length, "files");
